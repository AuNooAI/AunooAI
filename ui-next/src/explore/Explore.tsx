/** A tab that isn't rebuilt yet: says so and opens it on the old page. */
function NotYetRebuilt({ tab }: { tab: ExploreTab }) {
  return (
    <Panel title={tab.label}>
      <EmptyState
        icon="ArrowSquareOut"
        title="Still on the old Explore page"
        action={<Button iconStart={<Icon name="ArrowSquareOut" size="sm" />} onClick={() => openOnOldPage(tab.oldId)}>Open {tab.label}</Button>}
      >
        This tab hasn’t moved to the new design yet. It opens on the old page with the same data.
      </EmptyState>
    </Panel>
  );
}

/** AI disclosure at the foot of every tab, naming the model picked in the filter bar. */
function AIDisclosure({ model }: { model: string }) {
  return (
    <Panel title="AI technology disclosure" headingLevel={2}>
      <Text>
        Summaries, analysis, signals and narratives on this page are generated by AI ({model || 'the model picked above'}) from collected sources and may
        contain errors. Check the linked source before acting on it.
      </Text>
    </Panel>
  );
}

export function Explore() {
  const mods = useModules();
  // A dedicated Brand Watcher site shows only its tabs and no filter bar, as on the old page
  const dedicated = mods.dedicated ?? session.dedicatedBw;
  const visible = useMemo(
    () => TABS.filter((t) => (dedicated ? t.dedicated : !(t.module && !mods.isEnabled(t.module)))),
    [dedicated, mods],
  );
  const [tabId, navigate] = useTabRoute(dedicated ? 'brand-watcher' : 'news-feed');
  const tab = visible.find((t) => t.id === tabId) ?? visible[0];
  useEffect(() => {
    if (mods.dedicated !== null && tab && tab.id !== tabId) navigate(tab.id);
  }, [mods.dedicated, tab, tabId, navigate]);

  const ws = useExploreConfig();
  const modelLabel = ws.models.find((m) => m.id === ws.config.model)?.name ?? ws.config.model;
  const { toasts, notify } = useToasts();
  const [dialog, setDialog] = useState<null | 'schedule' | 'profiles'>(null);
  const [confirm, setConfirm] = useState<Confirm | null>(null);
  const feed = useRef<NewsFeedHandle>(null);
  const [refreshing, setRefreshing] = useState(false);
  const [sections, setSections] = useState<Sections>(loadSections);

  // Refresh reloads the article list, and on the News Feed regenerates the visible AI sections
  const refresh = async () => {
    setRefreshing(true);
    try {
      if (feed.current) await feed.current.refresh();
      else window.dispatchEvent(new Event('explore:refresh'));
      notify('Explore refreshed', 'ArrowClockwise');
    } finally {
      setRefreshing(false);
    }
  };

  return (
    <AppShell current="explore" page={tab?.label ?? 'Explore'} title="Explore" toasts={toasts}>
      <Stack gap="lg">
        {!dedicated && (
          <FilterBar
            ws={ws}
            busy={refreshing}
            onSchedule={() => setDialog('schedule')}
            onRefresh={() => void refresh()}
            onConfigureProfiles={() => setDialog('profiles')}
          />
        )}

        {tab && (
          <Tabs
            label="Explore sections"
            scrollable
            value={tab.id}
            onValueChange={navigate}
            items={visible.map((t) => ({ value: t.id, label: t.label, icon: <Icon name={t.icon} size="sm" /> }))}
            listAside={
              dedicated ? undefined : (
                <Stack direction="row" gap="sm" wrap={false}>
                  {tab.id === 'news-feed' && <SectionsPopover sections={sections} onChange={setSections} />}
                  <ModulesPopover
                    modules={mods.modules}
                    onToggle={(id, on) => mods.toggle(id, on).catch((e: unknown) => notify(`Not changed: ${e instanceof Error ? e.message : e}`))}
                    trigger={<IconButton icon={<Icon name="GearSix" size="sm" />} label="Analysis modules" />}
                  />
                </Stack>
              )
            }
          >
            {visible.map((t) => (
              <TabPanel key={t.id} value={t.id}>
                {t.id === tab.id && (
                  <Stack gap="lg">
                    {t.id === 'overview' && <Overview />}
                    {t.id === 'news-feed' && <NewsFeed ref={feed} sections={sections} ws={ws} notify={notify} askConfirm={setConfirm} />}
                    {t.id === 'timeline' && <Timeline notify={notify} askConfirm={setConfirm} />}
                    {t.id === 'brand-watcher' && <BrandWatcher notify={notify} askConfirm={setConfirm} voicesFeature={mods.features.bw_voices} />}
                    {t.id === 'market-monitor' && <MarketMonitor notify={notify} askConfirm={setConfirm} />}
                    {t.id === 'swiss-election' && <SwissElection notify={notify} />}
                    {t.id === 'emerging-topics' && <EmergingTopics topic={feedTopic(ws.config)} notify={notify} askConfirm={setConfirm} />}
                    {t.id === 'briefing-desk' && (
                      <BriefingDesk
                        model={ws.config.model}
                        profileName={ws.profiles.find((p) => p.id === ws.config.profileId)?.name}
                        persona={ws.config.persona}
                        notify={notify}
                        askConfirm={setConfirm}
                      />
                    )}
                    {t.id === 'geohotspots' && <GeoHotSpots model={ws.config.model} notify={notify} askConfirm={setConfirm} />}
                    {t.id === 'us-crisis-tracker' && <CrisisTracker model={ws.config.model} notify={notify} askConfirm={setConfirm} />}
                    {t.id === 'sciencewatch' && <ScienceWatch model={ws.config.model} notify={notify} askConfirm={setConfirm} />}
                    {t.id === 'threat-intelligence' && <ThreatIntel model={ws.config.model} notify={notify} askConfirm={setConfirm} />}
                    {t.id === 'saved' && <Saved topic={feedTopic(ws.config)} notify={notify} askConfirm={setConfirm} goToTab={navigate} />}
                    {t.id === 'observer-agents' && (
                      <ObserverAgents
                        topic={dedicated ? undefined : feedTopic(ws.config)}
                        topics={dedicated ? ws.topics.filter((n) => n.startsWith('Brand Monitoring')) : ws.topics}
                        dedicated={dedicated}
                        notify={notify}
                        askConfirm={setConfirm}
                      />
                    )}
                    {!t.built && <NotYetRebuilt tab={t} />}
                    {t.built && t.id !== 'overview' && <AIDisclosure model={modelLabel} />}
                  </Stack>
                )}
              </TabPanel>
            ))}
          </Tabs>
        )}
      </Stack>

      <ScheduleDialog open={dialog === 'schedule'} onOpenChange={(o) => setDialog(o ? 'schedule' : null)} notify={notify} />
      <ProfilesDialog
        open={dialog === 'profiles'}
        onOpenChange={(o) => setDialog(o ? 'profiles' : null)}
        profiles={ws.profiles}
        initialId={ws.config.profileId}
        onChanged={() => void ws.reloadProfiles()}
        notify={notify}
        askConfirm={setConfirm}
      />
      <ConfirmDialog confirm={confirm} onClose={() => setConfirm(null)} />
    </AppShell>
  );
}
