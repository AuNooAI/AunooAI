import { useEffect, useState } from 'react';
import { LineItems, Panel, Text } from '@aunoo/ui';
import { api, session } from '../../shell';

let deployed: Promise<string | null> | null = null;
/** Models this site has called recently (GET /api/ai-disclosure/models), fetched once per page. */
const deployedModels = () =>
  (deployed ??= api<{ models?: { name: string }[] }>('/api/ai-disclosure/models').then(
    (r) => (r.models?.length ? r.models.map((m) => m.name).join(', ') : null),
    () => null,
  ));

/** AI technology disclosure under each analysis (EU AI Act Art. 50): what made it, for what, by whom. */
export function Disclosure({ dashboard, purpose, model, generatedAt }: { dashboard: string; purpose: string; model?: string; generatedAt?: string }) {
  const [fallback, setFallback] = useState<string | null>(null);
  useEffect(() => {
    if (!model) void deployedModels().then(setFallback);
  }, [model]);
  const date = generatedAt ? new Date(generatedAt) : null;
  return (
    <Panel title="AI technology disclosure" headingLevel={2}>
      <LineItems
        label="AI technology disclosure"
        items={[
          { id: 'dashboard', label: 'Dashboard', amount: dashboard },
          { id: 'model', label: 'AI model', amount: model || fallback || 'the large language models configured for this site' },
          { id: 'purpose', label: 'Purpose', amount: purpose },
          ...(date && !Number.isNaN(date.getTime()) ? [{ id: 'date', label: 'Generated', amount: date.toLocaleString('en-GB', { dateStyle: 'medium', timeStyle: 'short' }) }] : []),
          { id: 'author', label: 'Author', amount: `Aunoo AI with ${session.user.username}${session.user.email ? ` (${session.user.email})` : ''}` },
        ]}
      />
      <Text variant="caption">Generated by AI from collected sources and may contain errors. Check the cited sources before acting on it.</Text>
    </Panel>
  );
}
