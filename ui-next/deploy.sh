#!/usr/bin/env bash
# Build the pages rebuilt on the aunoo design system and publish them.
#   - typechecks, then builds into static/aunoo-next/ (emptied first)
#   - turns each built entry HTML into templates/<entry>_next.html, adding the
#     session block the pages read as window.aunoo
# Restart is only needed when a route is added; templates auto-reload.
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(dirname "$HERE")"
cd "$HERE"
npx tsc --noEmit -p .
npx vite build
python3 - "$ROOT" <<'PY'
import sys, pathlib
root = pathlib.Path(sys.argv[1])
session = '''    <script>
      window.aunoo = {
        user: {
          username: {{ (session.get('user') or {}).get('username', 'User') | tojson }},
          email: {{ (session.get('user') or {}).get('email', '') | tojson }}
        },
        dedicatedBw: {{ (request.app.state.dedicated_bw | default(false)) | tojson }}
      };
    </script>
  </head>'''
for html in sorted((root / 'static/aunoo-next').glob('*.html')):
    s = html.read_text()
    assert s.count('</head>') == 1, html
    out = root / 'templates' / f'{html.stem}_next.html'
    out.write_text('{# Generated by ui-next/deploy.sh from static/aunoo-next/' + html.name + '. Do not edit. #}\n' + s.replace('</head>', session, 1))
    print('template:', out.relative_to(root))
PY
