class TenantClient:
    def __init__(self, port):
        self.base = f"http://127.0.0.1:{port}"
        self.opener = urllib.request.build_opener(
            urllib.request.HTTPCookieProcessor(http.cookiejar.CookieJar()))

    def _request(self, path, data=None, as_json=False, method=None):
        headers = {"X-Forwarded-Proto": "https"}
        body = None
        if data is not None:
            if as_json:
                body = json.dumps(data).encode()
                headers["Content-Type"] = "application/json"
            else:
                body = urllib.parse.urlencode(data).encode()
        req = urllib.request.Request(self.base + path, data=body,
                                     headers=headers, method=method)
        try:
            with self.opener.open(req, timeout=60) as resp:
                return resp.status, resp.read().decode()
        except urllib.error.HTTPError as e:
            return e.code, e.read().decode()

    def login(self, username, password):
        status, _ = self._request("/login", {"username": username, "password": password})
        # 200 = followed redirect chain; a session cookie is set either way
        if status not in (200, 302, 303, 307):
            die(f"login failed with HTTP {status}")

    def get_json(self, path):
        status, body = self._request(path)
        if status != 200:
            die(f"GET {path} -> HTTP {status}: {body[:300]}")
        return json.loads(body)

    def post_json(self, path, payload):
        status, body = self._request(path, payload, as_json=True)
        if status not in (200, 201):
            die(f"POST {path} -> HTTP {status}: {body[:300]}")
        return json.loads(body)

    def put(self, path):
        status, body = self._request(path, method="PUT")
        if status != 200:
            die(f"PUT {path} -> HTTP {status}: {body[:300]}")
        return json.loads(body)


