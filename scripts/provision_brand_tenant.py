def destroy(args):
    if os.geteuid() != 0:
        die("must run as root")
    n = names(args.slug)
    if n["dir"].rstrip("/") in (TEMPLATE_DIR, os.path.join(TENANTS_DIR, "bugfixing.aunoo.ai"),
                                os.path.join(TENANTS_DIR, "wiley.aunoo.ai"),
                                os.path.join(TENANTS_DIR, "wileytest.aunoo.ai")):
        die("refusing to destroy a protected tenant")
    if not args.yes:
        die("destroy requires --yes")
    log(f"destroying {n['domain']}")
    run(["systemctl", "disable", "--now", n["unit"]], check=False)
    if os.path.exists(n["unit_path"]):
        os.remove(n["unit_path"])
        run(["systemctl", "daemon-reload"])
    for p in (n["nginx_enabled"], n["nginx_avail"]):
        if os.path.exists(p) or os.path.islink(p):
            os.remove(p)
    run(["nginx", "-t"], check=False)
    run(["systemctl", "reload", "nginx"], check=False)
    run(["certbot", "delete", "--cert-name", n["domain"], "--non-interactive"], check=False)
    psql(f"DROP DATABASE IF EXISTS {n['db']} WITH (FORCE)", capture=False)
    psql(f"DROP ROLE IF EXISTS {n['db_user']}", capture=False)
    if os.path.isdir(n["dir"]):
        shutil.rmtree(n["dir"])
    if os.path.exists(n["creds"]):
        os.remove(n["creds"])
    log(f"destroyed {n['domain']}")


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)

    p = sub.add_parser("provision", help="stamp out a new dedicated BW tenant")
    p.add_argument("--slug", required=True, help="tenant slug (dir/db/user/domain prefix)")
    p.add_argument("--brand", help="brand display name, e.g. 'Acme Publishing' "
                                   "(required unless --data-from)")
    p.add_argument("--data-from", help="existing tenant (slug, domain or dir) whose DATA to "
                                       "clone: fresh DB dump, .env base (API keys carry over), "
                                       "config.json/provider_config.json; skips brand seeding "
                                       "and clears alert delivery targets on the clone")
    p.add_argument("--aliases", help="comma-separated brand aliases (legal names, tickers)")
    p.add_argument("--keywords", help="comma-separated extra monitoring keywords")
    p.add_argument("--port", type=int, help=f"backend port (default: first free in {PORT_RANGE.start}-{PORT_RANGE.stop - 1})")
    p.add_argument("--email", default="oliver.rochford@gmail.com", help="certbot contact email")
    p.add_argument("--dump", default=TEMPLATE_DUMP, help="golden template dump")
    p.add_argument("--skip-nginx", action="store_true", help="skip nginx + certbot (local testing)")
    p.set_defaults(func=provision)

    d = sub.add_parser("destroy", help="tear a tenant down completely")
    d.add_argument("--slug", required=True)
    d.add_argument("--yes", action="store_true", help="confirm destruction")
    d.set_defaults(func=destroy)

    args = ap.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
