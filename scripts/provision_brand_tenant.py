def log(msg):
    print(f"[provision] {msg}", flush=True)


def die(msg, code=1):
    print(f"[provision] ERROR: {msg}", file=sys.stderr, flush=True)
    sys.exit(code)


def run(cmd, check=True, capture=False, **kw):
    log("$ " + " ".join(cmd))
    return subprocess.run(cmd, check=check, text=True,
                          capture_output=capture, **kw)


def psql(sql, db="postgres", capture=True):
    r = run(["sudo", "-u", "postgres", "psql", "-d", db, "-v", "ON_ERROR_STOP=1",
             "-tAc", sql], capture=capture)
    return r.stdout.strip() if capture else None


def names(slug):
    return {
        "slug": slug,
        "dir": os.path.join(TENANTS_DIR, f"{slug}.aunoo.ai"),
        "db": slug,
        "db_user": f"{slug}_user",
        "domain": f"{slug}.aunoo.ai",
        "unit": f"{slug}.aunoo.ai.service",
        "unit_path": f"/etc/systemd/system/{slug}.aunoo.ai.service",
        "nginx_avail": f"/etc/nginx/sites-available/{slug}.aunoo.ai",
        "nginx_enabled": f"/etc/nginx/sites-enabled/{slug}.aunoo.ai",
        "creds": f"/var/tmp/{slug}_credentials.txt",
    }


def port_in_use(port):
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
        return s.connect_ex(("127.0.0.1", port)) == 0


def pick_port():
    for p in PORT_RANGE:
        if not port_in_use(p):
            return p
    die("no free port in range")


def wait_for_port(port, timeout=180):
    deadline = time.time() + timeout
    while time.time() < deadline:
        if port_in_use(port):
            return True
        time.sleep(3)
    return False


